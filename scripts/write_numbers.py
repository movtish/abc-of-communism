"""results/paper_numbers.json -> paper/numbers.tex. paper_numbers.py calls it at the end, run it alone if only the format changes.
In the text  \\N{key}   number with the decimals set in paper_numbers.py
             \\NA{key}  absolute value
             \\NI{key}  rounded to an integer
             \\NIA{key} absolute value, rounded"""
import os, sys, json
sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def fmt(v, d):
    s = f"{abs(v):.{d}f}"
    return ("$-$" + s) if v < 0 else s
def write_file(path, NUM, STR):
    with open(path, "w", encoding="utf-8") as f:
        f.write("% Generated by scripts/write_numbers.py from results/paper_numbers.json. Do not edit by hand.\n\\makeatletter\n")
        for k in sorted(NUM):
            v, d = NUM[k]; d = int(d)
            if v != v:   # not identified
                f.write("".join(f"\\@namedef{{{p}@{k}}}{{n.i.}}" for p in ("num", "numa", "numi", "numia")) + "\n"); continue
            f.write(f"\\@namedef{{num@{k}}}{{{fmt(v, d)}}}\\@namedef{{numa@{k}}}{{{abs(v):.{d}f}}}\\@namedef{{numi@{k}}}{{{fmt(round(v) + 0.0, 0)}}}\\@namedef{{numia@{k}}}{{{abs(round(v)):.0f}}}\n")
        for k in sorted(STR):
            f.write(f"\\@namedef{{num@{k}}}{{{STR[k].replace('<', '$<$')}}}\n")
        f.write("\\makeatother\n")
def write():
    J = json.load(open(f"{ROOT}/results/paper_numbers.json", encoding="utf-8")); NUM, STR = J["NUM"], J["STR"]
    os.makedirs(f"{ROOT}/paper", exist_ok=True); write_file(f"{ROOT}/paper/numbers.tex", NUM, STR)
    print("numbers.tex:", len(NUM), "numbers and", len(STR), "strings")
if __name__ == "__main__":
    write()
