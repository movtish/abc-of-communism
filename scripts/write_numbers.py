"""Write the numerical macros used by the English and Russian manuscripts.

Read results/paper_numbers.json after paper_numbers.py. The Russian output
uses decimal commas; the English abstract uses decimal points.
"""

import os, re, sys, json

sys.stdout.reconfigure(encoding="utf-8")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fmt(v, d, minus="$-$"):
    s = f"{abs(v):.{d}f}"
    return (minus + s) if v < 0 else s


def ru(s):
    if re.fullmatch(r"\d{1,3}(,\d{3})+", s):
        return s.replace(",", "~")  # thousands
    return s.replace(".", ",").replace("<", "$<$")


def write_file(path, NUM, STR, russian):
    minus = "\\m " if russian else "$-$"
    conv = (lambda s: s.replace(".", ",")) if russian else (lambda s: s)
    with open(path, "w", encoding="utf-8") as f:
        f.write(
            "% Generated by scripts/write_numbers.py from results/paper_numbers.json. Do not edit by hand.\n\\makeatletter\n"
        )
        for k in sorted(NUM):
            v, d = NUM[k]
            d = int(d)
            if v != v:  # not identified
                f.write(
                    "".join(
                        f"\\@namedef{{{p}@{k}}}{{n.i.}}"
                        for p in ("num", "numa", "numi", "numia")
                    )
                    + "\n"
                )
                continue
            f.write(
                f"\\@namedef{{num@{k}}}{{{conv(fmt(v, d, minus))}}}\\@namedef{{numa@{k}}}{{{conv(f'{abs(v):.{d}f}')}}}\\@namedef{{numi@{k}}}{{{fmt(round(v) + 0.0, 0, minus)}}}\\@namedef{{numia@{k}}}{{{abs(round(v)):.0f}}}"
                + (f"\\@namedef{{nume@{k}}}{{{fmt(v, d)}}}" if russian else "")
                + "\n"
            )  # Use English notation in the abstract of the Russian article.
        for k in sorted(STR):
            f.write(
                f"\\@namedef{{num@{k}}}{{{ru(STR[k]) if russian else STR[k].replace('<', '$<$')}}}\n"
            )
        f.write("\\makeatother\n")


def write():
    J = json.load(open(f"{ROOT}/results/paper_numbers.json", encoding="utf-8"))
    NUM, STR = J["NUM"], J["STR"]
    write_file(f"{ROOT}/paper/numbers.tex", NUM, STR, False)
    write_file(f"{ROOT}/jnea/numbers_ru.tex", NUM, STR, True)
    print(
        "numbers.tex and numbers_ru.tex:", len(NUM), "numbers and", len(STR), "strings"
    )


if __name__ == "__main__":
    write()
