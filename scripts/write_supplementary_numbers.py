"""Write manuscript number macros from the supplementary model tables."""

from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
A = ROOT / "supplementary/additional_data_analysis"
B = ROOT / "supplementary/likbez_1924_analysis"
values = {}
summary = pd.read_csv(A / "persistence_sample_summary.csv")
for row in summary[summary["sample"] == "paper_core5"].itertuples():
    values[f"followup.{row.area}.{row.sex}"] = (row.weighted_change_pp, 2)
models = pd.read_csv(A / "post1939_gender_gap_inference.csv")
urban = models[
    (models["sample"] == "paper_core5")
    & (models.area == "urban")
    & (models.weights == "population1939")
].iloc[0]
for field, digits in [("b", 2), ("ci_low_cr2", 2), ("ci_high_cr2", 2), ("wcr_p", 4)]:
    values["urban." + field] = (urban[field], digits)
policy = pd.read_csv(B / "policy1931_age_sensitivity.csv")
for row in policy[policy["sample"] == "all"].itertuples():
    tag = f"policy.{row.specification}.{row.contrast}"
    for field in ["b", "ci_low_cr2", "ci_high_cr2"]:
        values[tag + "." + field] = (getattr(row, field), 3)
main = pd.read_csv(ROOT / "methodology/results/estimates.csv", sep=";")
for label in ["female", "DDD"]:
    row = main[main.model == "main_" + label].iloc[0]
    values["main.clusters"] = (row.clusters, 0)
    for field in ["ci_low_cr2", "ci_high_cr2"]:
        values["main." + label + "." + field] = (row[field], 2)
lines = [
    "% Generated by scripts/write_supplementary_numbers.py; do not hand-edit.",
    r"\newcommand{\SN}[1]{\csname supp@#1\endcsname}",
]
for key, (v, digits) in values.items():
    lines.append(
        r"\expandafter\def\csname supp@"
        + key
        + r"\endcsname{"
        + f"{v:.{digits}f}"
        + "}"
    )
text = "\n".join(lines) + "\n"
for folder in ["paper", "jnea"]:
    (ROOT / folder / "supplementary_numbers.tex").write_text(text, encoding="utf-8")
print(f"Wrote {len(values)} supplementary manuscript numbers")
